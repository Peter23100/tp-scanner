// Writes the parity fixture: two sessions of one-minute bars for one symbol, from a seeded
// random walk, so it is identical every run. It covers premarket, RTH, a zero-volume RTH bar, a
// 5-minute gap, and a session change.
//
// Run once to create the fixture: node tools/parity/make_fixture.mjs
// The CSV is committed, and gen.mjs reads it. Rerunning this script rewrites the CSV identically.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../crates/tp-marketdata/tests/fixtures/parity_two_sessions.csv");

let s = 0x9e3779b9;
const rand = () => {
  s ^= s << 13; s >>>= 0;
  s ^= s >>> 17;
  s ^= s << 5; s >>>= 0;
  return s / 4294967296;
};
const r2 = (x) => Math.round(x * 100) / 100;
const pad = (n) => String(n).padStart(2, "0");

const lines = ["# generated by tools/parity/make_fixture.mjs - do not edit by hand",
  "symbol,start_ny,open,high,low,close,volume"];
let px = 42.0;
for (const date of ["2026-06-15", "2026-06-16"]) {
  for (let m = 9 * 60; m < 11 * 60; m++) {
    const h = Math.floor(m / 60), mi = m % 60;
    if (h === 10 && mi >= 20 && mi < 25) continue; // gap: no bars 10:20-10:24
    const rth = m >= 9 * 60 + 30;
    const open = r2(px);
    const close = r2(Math.max(1, px + (rand() - 0.5) * 0.6));
    const high = r2(Math.max(open, close) + rand() * 0.25);
    const low = r2(Math.min(open, close) - rand() * 0.25);
    let vol = Math.round((rth ? 20000 : 2000) * (0.2 + rand() * 1.8));
    if (h === 10 && mi === 5) vol = 0; // a zero-volume RTH bar
    px = close;
    lines.push(`XYZ,${date} ${pad(h)}:${pad(mi)}:00,${open},${high},${low},${close},${vol}`);
  }
}
writeFileSync(out, lines.join("\n") + "\n");
console.log(`wrote ${lines.length - 2} bars to ${out}`);
